#!/usr/bin/env python3
"""Reads WorldEdit's command classes (GPL-3.0, orig-src) and writes src/horizon_worldedit_core/engine/usage_table.rs:
for each @Command its names, switches, value flags and positional parameters, for Paper-style usage errors."""
import re, glob, sys, os
SRC = sys.argv[1]
OUT = sys.argv[2]
SKIP_TYPES = {"Actor", "Player", "LocalSession", "EditSession", "World", "Region", "Mask", "BlockVector3", "InjectedValueAccess", "Extent", "ParserContext"}
def split_top(s):
    out, depth, cur = [], 0, ""
    for c in s:
        if c in "(<{": depth += 1
        if c in ")>}": depth -= 1
        if c == "," and depth == 0:
            out.append(cur); cur = ""
        else:
            cur += c
    if cur.strip(): out.append(cur)
    return out
rows = []
group_names = {}
GROUPFILES = {"brush": ("BrushCommands", "ApplyBrushCommands", "PaintBrushCommands"), "tool": ("ToolCommands",), "schem": ("SchematicCommands",), "snap": ("SnapshotCommands", "LegacySnapshotCommands"), "pickaxe": ("SuperPickaxeCommands",), "we": ("WorldEditCommands",)}
for f in sorted(glob.glob(SRC + "/*.java")):
    b = os.path.basename(f)[:-5]
    for g, files in GROUPFILES.items():
        if b in files:
            for m in re.finditer(r'@Command\(\s*(.*?)\)\s*\n', open(f).read(), re.S):
                body = m.group(1)
                nm = re.search(r'name\s*=\s*"([^"]+)"', body)
                if not nm: continue
                al = re.search(r'aliases\s*=\s*\{(.*?)\}', body, re.S)
                names = [nm.group(1)] + (re.findall(r'"([^"]+)"', al.group(1)) if al else [])
                group_names.setdefault(g, [])
                group_names[g] += [n for n in names if not n.startswith("/")]
SKIPF = ("Brush", "Schematic", "Snapshot", "WorldEditCommands", "SuperPickaxe", "Scripting")
for f in sorted(glob.glob(SRC + "/*.java")):
    if any(k in os.path.basename(f) for k in SKIPF): continue
    s = open(f).read()
    for m in re.finditer(r'@Command\(\s*(.*?)\)\s*\n((?:\s*@[A-Za-z]+(?:\([^)]*\))?\s*\n)*)\s*public \w+ (\w+)\((.*?)\)\s*(?:throws[^{]*)?\{', s, re.S):
        body, params = m.group(1), m.group(4)
        name = re.search(r'name\s*=\s*"([^"]+)"', body).group(1)
        al = re.search(r'aliases\s*=\s*\{(.*?)\}', body, re.S)
        names = [name] + (re.findall(r'"([^"]+)"', al.group(1)) if al else [])
        names = [n.lstrip("/") for n in names]
        names = list(dict.fromkeys(n for n in names if n))
        switches, valued, pos = "", [], []
        for p in split_top(params):
            p = p.strip()
            if not p: continue
            sw = re.search(r'@Switch\(\s*(?:name\s*=\s*)?\'(.)\'', p)
            if sw: switches += sw.group(1); continue
            af = re.search(r"@ArgFlag\(\s*name\s*=\s*'(.)'", p)
            ty_name = re.search(r'([\w.<>\[\]]+)\s+(\w+)\s*$', re.sub(r'@\w+(\([^)]*\))?', '', p).strip())
            if not ty_name: continue
            ty, pname = ty_name.group(1), ty_name.group(2)
            if af: valued.append((af.group(1), pname, ty)); continue
            if "@Arg" not in p and "@Text" not in p: continue
            an = re.search(r'@Arg\([^)]*?\bname\s*=\s*"([^"]+)"', p)
            pname = an.group(1) if an else pname
            optional = bool(re.search(r'@Arg\([^)]*?\bdef\s*=', p))
            text = "@Text" in p
            pos.append((pname + ("..." if text else ""), optional, ty, text))
        rows.append((names, "".join(sorted(set(switches))), valued, pos))
def kind(t):
    t = t.replace("java.lang.", "")
    return {"int": "int", "Integer": "int", "double": "double", "Double": "double", "Pattern": "pattern", "Mask": "mask", "String": "text", "boolean": "text"}.get(t, "other")
with open(OUT, "w") as o:
    o.write("// Generated by tools/gen_usage.py from WorldEdit's command classes (GPL-3.0). Do not edit.\n")
    o.write("/// (names, switches, value flags (char, name), positional (name, optional, kind)).\n")
    o.write("pub type Row = (&'static [&'static str], &'static str, &'static [(char, &'static str)], &'static [(&'static str, bool, &'static str)]);\n")
    o.write("pub const TABLE: &[Row] = &[\n")
    for names, sw, valued, pos in rows:
        n = ", ".join('"%s"' % x for x in names)
        v = ", ".join("('%s', \"%s\")" % (c, nm) for c, nm, _ in valued)
        ps = ", ".join('("%s", %s, "%s")' % (nm, str(opt).lower(), kind(t)) for nm, opt, t, _ in pos)
        o.write("    (&[%s], \"%s\", &[%s], &[%s]),\n" % (n, sw, v, ps))
    o.write("];\n")
    o.write("/// Every sub-command word (names and aliases) of the group commands.\n")
    o.write("pub const GROUP_WORDS: &[(&str, &[&str])] = &[\n")
    for g, ns in group_names.items():
        o.write('    ("%s", &[%s]),\n' % (g, ", ".join('"%s"' % n for n in sorted(set(ns)))))
    o.write("];\n")
print(len(rows), "commands")
